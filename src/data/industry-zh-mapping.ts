export function mapIndustryToZh(industry: string | null | undefined): string | null {
    if (!industry) return null;
    const normalized = industry.trim();
    if (!normalized) return null;
    const match = INDUSTRY_ZH.find(([pattern]) => pattern.test(normalized));
    return match?.[1] ?? null;
}
